/**
 * Displays a requirement analysis (from the AI or the basic fallback).
 * Used on the customer review step and on the admin enquiry page.
 * Always shows a clear "preliminary" label and where the analysis came from.
 */
function Section({ title, children, plain = false }) {
  return (
    <section className={plain ? 'pb-5' : 'border-t border-line py-5 first:border-t-0 first:pt-0'}>
      <h3 className="mb-2.5 text-[15px] font-semibold text-navy-900">{title}</h3>
      {children}
    </section>
  );
}

function List({ items, empty }) {
  if (!items?.length) return <p className="text-sm text-muted">{empty}</p>;
  return (
    <ul className="space-y-1.5 text-[15px]">
      {items.map((t) => (
        <li key={t} className="flex gap-2.5">
          <span className="mt-2.5 h-1.5 w-1.5 shrink-0 rounded-full bg-sky" aria-hidden="true" />
          <span>{t}</span>
        </li>
      ))}
    </ul>
  );
}

export default function AnalysisPanel({ analysis, categoriesById = {}, audience = 'customer' }) {
  if (!analysis) return null;
  const isAi = analysis.source === 'ai';
  const nameOf = (id) => categoriesById[id]?.name || id;

  return (
    <div className="rounded-lg border border-line bg-white">
      <div className={`flex flex-wrap items-start justify-between gap-3 rounded-t-lg border-b border-line px-5 py-4 sm:px-6 ${isAi ? 'bg-mist' : 'bg-amber-50/60'}`}>
        <div>
          <p className="font-semibold text-navy-900">{isAi ? 'Preliminary AI suggestion' : 'Basic summary'}</p>
          <p className="mt-0.5 text-sm text-muted">
            {isAi
              ? audience === 'customer'
                ? 'Generated automatically from your description. Our team will review it and confirm what you actually need.'
                : `Generated by ${analysis.provider} (${analysis.model}). Not verified. Contains no pricing.`
              : audience === 'customer'
                ? 'AI analysis isn’t available right now, so this is a simple summary of your request. You can still submit it.'
                : 'AI was unavailable; this is a keyword-based summary produced by the system.'}
          </p>
        </div>
        <span className="rounded-full bg-white px-2.5 py-0.5 text-xs font-medium text-muted ring-1 ring-line">Not a quotation</span>
      </div>

      <div className="px-5 py-5 sm:px-6">
        <Section title="Summary">
          <p className="text-[15px] leading-relaxed">{analysis.projectSummary}</p>
        </Section>

        <Section title="What we understood">
          <List items={analysis.identifiedRequirements} empty="No specific requirements identified." />
        </Section>

        <Section title="Relevant services">
          {analysis.relevantServiceCategories?.length ? (
            <ul className="flex flex-wrap gap-2">
              {analysis.relevantServiceCategories.map((id) => (
                <li key={id} className="rounded-md bg-mist px-2.5 py-1 text-sm font-medium text-navy-800">
                  {nameOf(id)}
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-sm text-muted">None identified.</p>
          )}
        </Section>

        <Section title="Possible solution components">
          {analysis.suggestedComponents?.length ? (
            <ul className="divide-y divide-line rounded-md border border-line">
              {analysis.suggestedComponents.map((c) => (
                <li key={`${c.category}-${c.name}`} className="grid gap-1 px-4 py-3 sm:grid-cols-[1fr_auto] sm:gap-4">
                  <div>
                    <p className="font-medium">{c.name}</p>
                    {c.purpose && <p className="text-sm text-muted">{c.purpose}</p>}
                  </div>
                  <span className="text-sm text-muted sm:text-right">{nameOf(c.category)}</span>
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-sm text-muted">No components suggested.</p>
          )}
        </Section>

        <div className="grid gap-x-8 border-t border-line pt-5 md:grid-cols-2">
          <Section plain title="Information still needed">
            <List items={analysis.missingInformation} empty="Nothing obvious is missing." />
          </Section>
          <Section plain title={audience === 'customer' ? 'Questions our team may ask you' : 'Suggested follow-up questions'}>
            <List items={analysis.followUpQuestions} empty="No follow-up questions." />
          </Section>
        </div>
      </div>
    </div>
  );
}
